package lifeline.api.demo;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import lifeline.api.model.*;
import lifeline.api.repository.*;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.CommandLineRunner;
import org.springframework.context.annotation.Profile;
import org.springframework.core.io.ClassPathResource;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

import java.io.File;
import java.io.InputStream;
import java.time.Instant;
import java.time.LocalDate;
import java.util.Iterator;
import java.util.Map;

/**
 * Loads synthetic demo seed data generated by lifeline-eval into PostgreSQL when
 * running under the 'demo' profile.
 * <p>
 * Architectural rule: lifeline-api must never import lifeline-sim or lifeline-eval.
 * This class reads only the exported seed JSON file and uses Spring Boot's Jackson ObjectMapper.
 */
@Component
@Profile("demo")
public class DemoDataLoader implements CommandLineRunner {

    private static final Logger log = LoggerFactory.getLogger(DemoDataLoader.class);

    private final UserRepository userRepository;
    private final DonorProfileRepository donorProfileRepository;
    private final BankRepository bankRepository;
    private final BankInventoryRepository bankInventoryRepository;
    private final BloodRequestRepository bloodRequestRepository;
    private final PasswordEncoder passwordEncoder;
    private final ObjectMapper objectMapper;

    public DemoDataLoader(
        UserRepository userRepository,
        DonorProfileRepository donorProfileRepository,
        BankRepository bankRepository,
        BankInventoryRepository bankInventoryRepository,
        BloodRequestRepository bloodRequestRepository,
        PasswordEncoder passwordEncoder,
        ObjectMapper objectMapper
    ) {
        this.userRepository = userRepository;
        this.donorProfileRepository = donorProfileRepository;
        this.bankRepository = bankRepository;
        this.bankInventoryRepository = bankInventoryRepository;
        this.bloodRequestRepository = bloodRequestRepository;
        this.passwordEncoder = passwordEncoder;
        this.objectMapper = objectMapper;
    }

    @Override
    @Transactional
    public void run(String... args) throws Exception {
        log.info("Checking demo data seeding under 'demo' profile...");

        ensureDefaultAccounts();

        JsonNode rootNode = loadSeedJson();
        if (rootNode == null) {
            log.warn("No demo seed JSON found at data/demo_seed.json or classpath:demo_seed.json. Skipping demo seeding.");
            return;
        }

        seedBanks(rootNode.get("banks"));
        seedDonors(rootNode.get("donors"));
        seedSampleRequests();

        log.info("Demo data seeding completed successfully.");
    }

    private void ensureDefaultAccounts() {
        // Ensure admin account exists with active status and valid password (admin / admin123)
        userRepository.findByUsername("admin").ifPresentOrElse(admin -> {
            admin.setPasswordHash(passwordEncoder.encode("admin123"));
            admin.setStatus(UserStatus.ACTIVE);
            userRepository.save(admin);
            log.info("Verified demo admin user: admin / admin123");
        }, () -> {
            UserEntity admin = new UserEntity("admin", "admin@lifeline.test", passwordEncoder.encode("admin123"), Role.ADMIN);
            userRepository.save(admin);
            log.info("Seeded default admin user: admin / admin123");
        });

        // Ensure staff_central account exists with active status and valid password (staff_central / password123)
        userRepository.findByUsername("staff_central").ifPresentOrElse(staff -> {
            staff.setPasswordHash(passwordEncoder.encode("password123"));
            staff.setStatus(UserStatus.ACTIVE);
            userRepository.save(staff);
            log.info("Verified demo staff user: staff_central / password123");
        }, () -> {
            UserEntity staff = new UserEntity("staff_central", "staff1@lifeline.test", passwordEncoder.encode("password123"), Role.BANK_STAFF);
            userRepository.save(staff);
            log.info("Seeded default staff user: staff_central / password123");
        });

        // Ensure donor_arjun account exists with active status and valid password (donor_arjun / SecurePass123!)
        userRepository.findByUsername("donor_arjun").ifPresentOrElse(donorUser -> {
            donorUser.setPasswordHash(passwordEncoder.encode("SecurePass123!"));
            donorUser.setStatus(UserStatus.ACTIVE);
            userRepository.save(donorUser);
            log.info("Verified demo donor user: donor_arjun / SecurePass123!");
        }, () -> {
            UserEntity donorUser = new UserEntity("donor_arjun", "arjun@lifeline.test", passwordEncoder.encode("SecurePass123!"), Role.DONOR);
            donorUser = userRepository.save(donorUser);

            DonorProfileEntity profile = new DonorProfileEntity();
            profile.setUser(donorUser);
            profile.setBloodGroup("O_POS");
            profile.setSex("MALE");
            profile.setHomeZone("Z01");
            profile.setLastDonationDate(LocalDate.now().minusDays(150));
            profile.setAvailable(true);
            profile.setCurrentZone("Z01");
            profile.setLocationConfirmedAt(Instant.now());
            donorProfileRepository.save(profile);
            log.info("Seeded default donor user: donor_arjun / SecurePass123!");
        });
    }

    private JsonNode loadSeedJson() {
        try {
            File externalFile = new File("data/demo_seed.json");
            if (externalFile.exists()) {
                log.info("Loading demo seed from external file: {}", externalFile.getAbsolutePath());
                return objectMapper.readTree(externalFile);
            }

            ClassPathResource resource = new ClassPathResource("demo_seed.json");
            if (resource.exists()) {
                log.info("Loading demo seed from classpath:demo_seed.json");
                try (InputStream is = resource.getInputStream()) {
                    return objectMapper.readTree(is);
                }
            }
        } catch (Exception e) {
            log.error("Failed to parse demo seed JSON: {}", e.getMessage(), e);
        }
        return null;
    }

    private void seedBanks(JsonNode banksNode) {
        if (banksNode == null || !banksNode.isArray()) {
            return;
        }

        if (bankRepository.count() > 0) {
            log.info("Banks already exist (count={}); skipping bank seeding.", bankRepository.count());
            return;
        }

        for (JsonNode b : banksNode) {
            String name = b.path("name").asText("Blood Bank");
            String zone = b.path("zone").asText("Z01");
            String contactPhone = b.path("contactPhone").asText("+91-22-2000-5000");
            String contactEmail = b.path("contactEmail").asText("info@lifeline.test");
            double lat = b.path("latitude").asDouble(28.6139);
            double lon = b.path("longitude").asDouble(77.2090);

            BankEntity bank = new BankEntity(name, zone, contactPhone, contactEmail, lat, lon);
            bank = bankRepository.save(bank);

            JsonNode stockNode = b.get("stock");
            if (stockNode != null && stockNode.isObject()) {
                Iterator<Map.Entry<String, JsonNode>> fields = stockNode.fields();
                while (fields.hasNext()) {
                    Map.Entry<String, JsonNode> entry = fields.next();
                    String bg = entry.getKey();
                    int units = entry.getValue().asInt(0);
                    BankInventoryEntity inv = new BankInventoryEntity(bank, bg, units);
                    bankInventoryRepository.save(inv);
                }
            }
        }
        log.info("Seeded {} banks with inventory.", banksNode.size());
    }

    private void seedDonors(JsonNode donorsNode) {
        if (donorsNode == null || !donorsNode.isArray()) {
            return;
        }

        // Count existing donors
        long existingDonors = donorProfileRepository.count();
        if (existingDonors > 5) {
            log.info("Donors already exist (count={}); skipping donor seeding.", existingDonors);
            return;
        }

        String defaultDonorPassword = passwordEncoder.encode("DemoPassword123!");

        int seeded = 0;
        for (JsonNode d : donorsNode) {
            String username = d.path("username").asText();
            if (username.isEmpty() || userRepository.existsByUsername(username)) {
                continue;
            }

            String email = d.path("email").asText(username + "@lifeline.test");
            UserEntity user = new UserEntity(username, email, defaultDonorPassword, Role.DONOR);
            user = userRepository.save(user);

            DonorProfileEntity profile = new DonorProfileEntity();
            profile.setUser(user);
            profile.setBloodGroup(d.path("bloodGroup").asText("O_POS"));
            profile.setSex(d.path("sex").asText("MALE"));
            profile.setHomeZone(d.path("homeZone").asText("Z01"));

            if (d.hasNonNull("lastDonationDate")) {
                try {
                    profile.setLastDonationDate(LocalDate.parse(d.get("lastDonationDate").asText()));
                } catch (Exception ignored) {
                }
            }

            profile.setAvailable(d.path("available").asBoolean(true));
            profile.setPaused(d.path("paused").asBoolean(false));

            if (d.hasNonNull("currentZone")) {
                profile.setCurrentZone(d.get("currentZone").asText());
            }
            if (d.hasNonNull("locationConfirmedAt")) {
                try {
                    profile.setLocationConfirmedAt(Instant.parse(d.get("locationConfirmedAt").asText()));
                } catch (Exception ignored) {
                }
            }

            profile.setTotalContacts(d.path("totalContacts").asInt(0));
            profile.setTotalAccepts(d.path("totalAccepts").asInt(0));
            profile.setTotalDeclines(d.path("totalDeclines").asInt(0));
            profile.setTotalNoResponses(d.path("totalNoResponses").asInt(0));

            donorProfileRepository.save(profile);
            seeded++;
        }
        log.info("Seeded {} synthetic donors with observable profiles.", seeded);
    }

    private void seedSampleRequests() {
        if (bloodRequestRepository.count() > 0) {
            return;
        }

        BloodRequestEntity pending = new BloodRequestEntity();
        pending.setBloodGroup("O_POS");
        pending.setUnitsRequested(2);
        pending.setUrgency("URGENT");
        pending.setZone("Z01");
        pending.setPatientReference("REF-PATIENT-101");
        pending.setStatus(RequestStatus.PENDING_REVIEW);
        pending.setSource(RequestSource.PUBLIC);
        pending.setDeadline(Instant.now().plusSeconds(7200));
        pending.setContactNumber("9876543210");
        bloodRequestRepository.save(pending);

        BloodRequestEntity openReq = new BloodRequestEntity();
        openReq.setBloodGroup("B_POS");
        openReq.setUnitsRequested(1);
        openReq.setUrgency("CRITICAL");
        openReq.setZone("Z02");
        openReq.setPatientReference("REF-PATIENT-202");
        openReq.setStatus(RequestStatus.OPEN);
        openReq.setSource(RequestSource.STAFF);
        openReq.setDeadline(Instant.now().plusSeconds(3600));
        userRepository.findByUsername("staff_central").ifPresent(openReq::setReviewer);
        openReq.setReviewedAt(Instant.now());
        bloodRequestRepository.save(openReq);

        log.info("Seeded sample requests for review and matching workflows.");
    }
}
